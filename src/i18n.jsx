const dicts = { en, fr };
const pickInitial = () => {
  try {
    const saved = localStorage.getItem('chiaramail.lang');
    if (saved && dicts[saved]) return saved;
  } catch { /* ignore */ }
  const nav = (navigator.languages || [navigator.language || 'en']).map((l) => l.slice(0, 2));
  return nav.find((l) => dicts[l]) || 'en';
};

const I18n = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(pickInitial);
  const t = useCallback((key, vars) => {
    let s = dicts[lang][key] ?? en[key] ?? key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
    return s;
  }, [lang]);
  const value = useMemo(() => ({
    lang,
    t,
    toggle: () => {
      const next = lang === 'en' ? 'fr' : 'en';
      try { localStorage.setItem('chiaramail.lang', next); } catch { /* ignore */ }
      document.documentElement.lang = next;
      setLang(next);
    },
    formatShort: (d) => {
      if (!d) return '';
      const loc = lang === 'fr' ? 'fr-FR' : 'en-GB';
      const now = new Date();
      if (d.toDateString() === now.toDateString()) return new Intl.DateTimeFormat(loc, { hour: '2-digit', minute: '2-digit' }).format(d);
      if (d.getFullYear() === now.getFullYear()) return new Intl.DateTimeFormat(loc, { day: 'numeric', month: 'short' }).format(d);
      return new Intl.DateTimeFormat(loc, { day: '2-digit', month: '2-digit', year: 'numeric' }).format(d);
    },
    formatDate: (d) => (d ? new Intl.DateTimeFormat(lang === 'fr' ? 'fr-FR' : 'en-GB', {
      day: 'numeric', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit',
    }).format(d) : ''),
  }), [lang, t]);
  return <I18n.Provider value={value}>{children}</I18n.Provider>;
}

export const useI18n = () => useContext(I18n);
